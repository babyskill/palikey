#!/usr/bin/env python3
"""
generate_kmn.py — Generate Keyman keyboard (.kmn) source from schemes.json.

Guarantees that Keyman transliteration rules never drift from palikey-engine.
Implements PaliTelex and Velthuis input conventions using Keyman stores.

Usage:
    python3 generate_kmn.py [--input ../shared/schemes.json] [--output palikey.kmn]
"""

import json
import os
import sys
from pathlib import Path


def char_to_kmn(c: str) -> str:
    """Format a character as Keyman literal or U+XXXX notation."""
    code = ord(c)
    if 32 <= code <= 126 and c not in ("'", '"', "\\"):
        return f"'{c}'"
    return f"U+{code:04X}"


def main():
    script_dir = Path(__file__).resolve().parent
    default_json = script_dir.parent / "shared" / "schemes.json"
    default_kmn = script_dir / "palikey.kmn"

    json_path = Path(sys.argv[1]) if len(sys.argv) > 1 and not sys.argv[1].startswith("-") else default_json
    kmn_path = Path(sys.argv[2]) if len(sys.argv) > 2 and not sys.argv[2].startswith("-") else default_kmn

    if not json_path.exists():
        print(f"Error: {json_path} does not exist", file=sys.stderr)
        sys.exit(1)

    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    schemes = data.get("schemes", {})
    velthuis = schemes.get("velthuis", {}).get("mappings", [])
    palitelex = schemes.get("palitelex", {}).get("mappings", [])

    # Classify rules
    # 1. Vowel doubling rules (from either, usually identical: aa->ā, ii->ī, uu->ū, ee->ē, oo->ō)
    vowel_rules = []
    seen_seq = set()
    for rule in palitelex:
        seq = rule["sequence"]
        target = rule["char"]
        if len(seq) == 2 and seq[0].lower() in "aeiou" and seq[1].lower() in "aeiou" and seq[0].lower() == seq[1].lower():
            if seq not in seen_seq:
                seen_seq.add(seq)
                vowel_rules.append((seq[0], seq[1], target, rule["sequence"]))

    # 2. PaliTelex suffix rules:
    # 2-char suffix: e.g. tx -> ṭ, mx -> ṃ, nw -> ñ
    telex2_rules = []
    # 3-char suffix: e.g. ngw -> ṅ, ngx -> ṅ
    telex3_rules = []

    for rule in palitelex:
        seq = rule["sequence"]
        target = rule["char"]
        if seq in seen_seq:
            continue
        if len(seq) == 2 and seq[1] in "xwXWyY":
            telex2_rules.append((seq[0], seq[1], target, seq))
        elif len(seq) == 3 and seq[2] in "xwXWyY":
            telex3_rules.append((seq[0], seq[1], seq[2], target, seq))

    # 3. Velthuis prefix rules:
    # 2-char prefix: e.g. .t -> ṭ, "n -> ṅ, ~n -> ñ
    velthuis2_rules = []
    # 3-char prefix: e.g. .rr -> ṝ, .ll -> ḹ
    velthuis3_rules = []

    for rule in velthuis:
        seq = rule["sequence"]
        target = rule["char"]
        if seq in seen_seq:
            continue
        if len(seq) == 2 and seq[0] in ".~\"'":
            velthuis2_rules.append((seq[0], seq[1], target, seq))
        elif len(seq) == 3 and seq[0] in ".~\"'":
            velthuis3_rules.append((seq[0], seq[1], seq[2], target, seq))

    # Build Keyman content
    lines = [
        "c =====================================================================",
        "c PaliKey — Cross-platform Pāḷi Keyboard for Keyman",
        "c Auto-generated from shared/schemes.json by generate_kmn.py.",
        "c Do not edit this file directly; edit schemes.rs / schemes.json instead.",
        "c",
        "c Supports both PaliTelex and Velthuis input conventions converging to",
        "c identical Unicode output.",
        "c =====================================================================",
        "",
        "store(&NAME) 'PaliKey'",
        "store(&KEYBOARDVERSION) '0.1.0'",
        "store(&COPYRIGHT) 'MIT License'",
        "store(&MESSAGE) 'Cross-platform Pāḷi input method supporting PaliTelex and Velthuis conventions.'",
        "store(&TARGETS) 'any'",
        "store(&BITMAP) 'palikey.ico'",
        "store(&VISUALKEYBOARD) 'palikey.kvks'",
        "",
        "begin Unicode > use(main)",
        "",
        "group(main) using keys",
        "",
    ]

    # --- 1. Vowel doubling ---
    lines.append("c ---------------------------------------------------------------------")
    lines.append("c 1. VOWEL DOUBLING (PaliTelex & Velthuis shared: aa->ā, ii->ī, uu->ū)")
    lines.append("c ---------------------------------------------------------------------")
    v_ctx = " ".join(char_to_kmn(r[0]) for r in vowel_rules)
    v_key = " ".join(char_to_kmn(r[1]) for r in vowel_rules)
    v_out = " ".join(char_to_kmn(r[2]) for r in vowel_rules)

    lines.append(f"store(vowel_ctx) {v_ctx}")
    lines.append(f"store(vowel_key) {v_key}")
    lines.append(f"store(vowel_out) {v_out}")
    lines.append("any(vowel_ctx) + any(vowel_key) > index(vowel_out, 1)")
    lines.append("")

    # --- 2. Velthuis prefix 2-char ---
    lines.append("c ---------------------------------------------------------------------")
    lines.append("c 2. VELTHUIS PREFIX RULES (.t->ṭ, .d->ḍ, .n->ṇ, .m->ṃ, \"n->ṅ, ~n->ñ)")
    lines.append("c ---------------------------------------------------------------------")
    v2_pfx = " ".join(char_to_kmn(r[0]) for r in velthuis2_rules)
    v2_key = " ".join(char_to_kmn(r[1]) for r in velthuis2_rules)
    v2_out = " ".join(char_to_kmn(r[2]) for r in velthuis2_rules)

    lines.append(f"store(velthuis2_pfx) {v2_pfx}")
    lines.append(f"store(velthuis2_key) {v2_key}")
    lines.append(f"store(velthuis2_out) {v2_out}")
    lines.append("any(velthuis2_pfx) + any(velthuis2_key) > index(velthuis2_out, 1)")
    lines.append("")

    # --- 3. Velthuis prefix 3-char ---
    if velthuis3_rules:
        lines.append("c ---------------------------------------------------------------------")
        lines.append("c 3. VELTHUIS 3-CHAR EXTENDED RULES (.rr->ṝ, .ll->ḹ)")
        lines.append("c ---------------------------------------------------------------------")
        v3_c1 = " ".join(char_to_kmn(r[0]) for r in velthuis3_rules)
        v3_c2 = " ".join(char_to_kmn(r[1]) for r in velthuis3_rules)
        v3_key = " ".join(char_to_kmn(r[2]) for r in velthuis3_rules)
        v3_out = " ".join(char_to_kmn(r[3]) for r in velthuis3_rules)

        lines.append(f"store(velthuis3_c1)  {v3_c1}")
        lines.append(f"store(velthuis3_c2)  {v3_c2}")
        lines.append(f"store(velthuis3_key) {v3_key}")
        lines.append(f"store(velthuis3_out) {v3_out}")
        lines.append("any(velthuis3_c1) any(velthuis3_c2) + any(velthuis3_key) > index(velthuis3_out, 1)")
        lines.append("")

    # --- 4. PaliTelex suffix 2-char ---
    lines.append("c ---------------------------------------------------------------------")
    lines.append("c 4. PALITELEX SUFFIX RULES (tx->ṭ, dx->ḍ, nx->ṇ, mx->ṃ, lx->ḷ, nw->ñ)")
    lines.append("c ---------------------------------------------------------------------")
    t2_ctx = " ".join(char_to_kmn(r[0]) for r in telex2_rules)
    t2_key = " ".join(char_to_kmn(r[1]) for r in telex2_rules)
    t2_out = " ".join(char_to_kmn(r[2]) for r in telex2_rules)

    lines.append(f"store(telex2_ctx) {t2_ctx}")
    lines.append(f"store(telex2_key) {t2_key}")
    lines.append(f"store(telex2_out) {t2_out}")
    lines.append("any(telex2_ctx) + any(telex2_key) > index(telex2_out, 1)")
    lines.append("")

    # --- 5. PaliTelex suffix 3-char ---
    if telex3_rules:
        lines.append("c ---------------------------------------------------------------------")
        lines.append("c 5. PALITELEX 3-CHAR RULES (ngw->ṅ, ngx->ṅ, rrx->ṝ, llx->ḹ)")
        lines.append("c ---------------------------------------------------------------------")
        t3_c1 = " ".join(char_to_kmn(r[0]) for r in telex3_rules)
        t3_c2 = " ".join(char_to_kmn(r[1]) for r in telex3_rules)
        t3_key = " ".join(char_to_kmn(r[2]) for r in telex3_rules)
        t3_out = " ".join(char_to_kmn(r[3]) for r in telex3_rules)

        lines.append(f"store(telex3_c1)  {t3_c1}")
        lines.append(f"store(telex3_c2)  {t3_c2}")
        lines.append(f"store(telex3_key) {t3_key}")
        lines.append(f"store(telex3_out) {t3_out}")
        lines.append("any(telex3_c1) any(telex3_c2) + any(telex3_key) > index(telex3_out, 1)")
        lines.append("")

    # --- 6. Repeat-key escape (Undo composition on repeating trigger) ---
    lines.append("c ---------------------------------------------------------------------")
    lines.append("c 6. REPEAT-KEY ESCAPE (Undo composition if trigger key is repeated)")
    lines.append("c ---------------------------------------------------------------------")
    # Vowels: ā + a -> aaa
    v_undo_ctx = " ".join(char_to_kmn(r[2]) for r in vowel_rules)
    v_undo_key = " ".join(char_to_kmn(r[1]) for r in vowel_rules)
    # Output is raw sequence + repeat key
    v_undo_out = " ".join(f"'{r[3]}{r[1]}'" for r in vowel_rules)
    lines.append(f"store(v_undo_ctx) {v_undo_ctx}")
    lines.append(f"store(v_undo_key) {v_undo_key}")
    lines.append(f"store(v_undo_out) {v_undo_out}")
    lines.append("any(v_undo_ctx) + any(v_undo_key) > index(v_undo_out, 1)")
    lines.append("")

    # Telex 2-char undo: ṭ + x -> txx
    t2_undo_ctx = " ".join(char_to_kmn(r[2]) for r in telex2_rules)
    t2_undo_key = " ".join(char_to_kmn(r[1]) for r in telex2_rules)
    t2_undo_out = " ".join(f"'{r[3]}{r[1]}'" for r in telex2_rules)
    lines.append(f"store(t2_undo_ctx) {t2_undo_ctx}")
    lines.append(f"store(t2_undo_key) {t2_undo_key}")
    lines.append(f"store(t2_undo_out) {t2_undo_out}")
    lines.append("any(t2_undo_ctx) + any(t2_undo_key) > index(t2_undo_out, 1)")
    lines.append("")

    # Telex 3-char undo: ṅ + w -> ngww
    if telex3_rules:
        t3_undo_ctx = " ".join(char_to_kmn(r[3]) for r in telex3_rules)
        t3_undo_key = " ".join(char_to_kmn(r[2]) for r in telex3_rules)
        t3_undo_out = " ".join(f"'{r[4]}{r[2]}'" for r in telex3_rules)
        lines.append(f"store(t3_undo_ctx) {t3_undo_ctx}")
        lines.append(f"store(t3_undo_key) {t3_undo_key}")
        lines.append(f"store(t3_undo_out) {t3_undo_out}")
        lines.append("any(t3_undo_ctx) + any(t3_undo_key) > index(t3_undo_out, 1)")
        lines.append("")

    # --- 7. Punctuation prefix escapes (double prefix -> literal punctuation) ---
    lines.append("c ---------------------------------------------------------------------")
    lines.append("c 7. PREFIX ESCAPES (Double-tap prefix outputs literal character)")
    lines.append("c ---------------------------------------------------------------------")
    lines.append("'.' + '.' > '..'")
    lines.append("'\"' + '\"' > '\"\"'")
    lines.append("'~' + '~' > '~~'")
    lines.append("'\\' + '\\' > '\\\\'")
    lines.append("")

    content = "\n".join(lines) + "\n"

    kmn_path.parent.mkdir(parents=True, exist_ok=True)
    with open(kmn_path, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"Generated {kmn_path} ({len(content)} bytes)")


if __name__ == "__main__":
    main()
